-- 남은 운영 리스크를 적어 둔다. 코드로 막지 않은 것들이다.
--
--   레이트리밋이 없다. 로그인 사용자가 댓글을 초당 여러 개 달 수 있다.
--   신고·차단이 없다. 편집장이 comments.deleted_at 을 채워 숨길 수는 있다
--   (comments_update_own 이 is_admin 을 허용한다).
