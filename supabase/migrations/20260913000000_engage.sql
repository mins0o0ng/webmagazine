-- applied-if: select exists (select 1 from pg_constraint where conname = 'comments_body_length')
-- M3 좋아요 · M3-1 댓글
--
-- 스키마는 M1 부터 있었다(likes, comments, 카운터 트리거). 이 파일이 더하는 것은
-- 정책과 제약뿐이다 — 테이블을 새로 만들지 않는다.
--
-- 이 파일은 몇 번을 돌려도 결과가 같다.

-- ---------------------------------------------------------------------------
-- 1. 누가 무엇에 좋아요했는지는 공개하지 않는다
-- ---------------------------------------------------------------------------
--
-- M1 의 정책은 `for select using (true)` 였다. anon 키는 브라우저에 노출되므로
-- 그 상태로 좋아요 기능을 열면 누구나 likes 테이블을 통째로 읽어
-- "어느 사람이 어떤 글에 좋아요했는지" 를 전부 뽑을 수 있다.
-- 에세이·연애 카테고리가 있는 매거진에서 이건 프라이버시 사고다.
--
-- 개수는 이미 posts.like_count 에 비정규화돼 있다(§3.2). 화면이 likes 에서
-- 알아야 할 것은 "내가 눌렀나" 하나뿐이므로, 본인 행만 보이면 충분하다.

drop policy if exists likes_read_all on likes;

create policy likes_read_self on likes
  for select using (
    auth.uid() is not null
    and actor_key = auth.uid()::text
  );

-- 비로그인 좋아요는 만들지 않는다.
--
-- 기획안 §3.2 는 쿠키 UUID 를 actor_key 에 넣자고 했지만, 쿠키 UUID 는 시크릿
-- 창으로 무한히 새로 만들 수 있고 IP 해시는 개인정보 문제와 NAT 뒤 사용자 문제를
-- 동시에 만든다. 기고를 초대제로 좁힌 지면에서 좋아요만 익명으로 여는 것도
-- 일관되지 않는다. 로그인 사용자만 누른다.
--
-- 그래서 likes_insert_self / likes_delete_self(마이그레이션 1)를 그대로 둔다.
-- 서버 액션이 service_role 로 우회할 일도 없다 — 세션 클라이언트로 충분하다.

-- ---------------------------------------------------------------------------
-- 2. 댓글 길이
-- ---------------------------------------------------------------------------
--
-- 애플리케이션에도 같은 검사가 있지만, 형식은 DB 에서도 강제한다.
-- 서버 액션을 우회해 anon 키로 직접 insert 하는 경로가 남아 있기 때문이다
-- (RLS 는 "본인 이름으로만" 까지만 보장하지, 그 내용이 말이 되는지는 보지 않는다).

alter table comments
  drop constraint if exists comments_body_length;

alter table comments
  add constraint comments_body_length
  check (char_length(btrim(body)) between 1 and 2000);

-- ---------------------------------------------------------------------------
-- 3. 댓글 목록 인덱스
-- ---------------------------------------------------------------------------
--
-- comments_post_idx (post_id, created_at) 는 마이그레이션 1 에 있다. 화면은
-- 지워진 댓글을 빼고 읽으므로 부분 인덱스를 하나 더 둔다.

create index if not exists comments_visible_idx
  on comments (post_id, created_at)
  where deleted_at is null;

